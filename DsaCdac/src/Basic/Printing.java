package Basic;

public class Printing {
	public static void main(String [] args) {
		int a=10;
		int b=20;
		
		System.out.println(b+" is b and a is "+a);
		System.out.println("10+20 ="+(a+b));
		System.out.println("a is "+a+" and 2xa="+(2*a));
		System.out.println("10*20="+(a*b));
		System.out.print("line1:a is "+a);
		System.out.print("\nline2:b is "+b);
		
	}
}
